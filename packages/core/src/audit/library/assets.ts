import type { Assertion, AreaId, EngagementKind, Industry, Procedure } from "../types";

type Ind = Exclude<Industry, "generic">;
type FU = [text: string, why: string];

/** Compact constructor so the library below stays readable. */
function p(
  area: AreaId,
  slug: string,
  kinds: EngagementKind[],
  text: string,
  why: string,
  assertions: Assertion[],
  followUps: FU[],
  opts: { industries?: Ind[]; core?: boolean } = {},
): Procedure {
  return {
    id: `${area}.${slug}`,
    area,
    text,
    why,
    assertions,
    kinds,
    ...(opts.industries ? { industries: opts.industries } : {}),
    ...(opts.core ? { core: true } : {}),
    followUps: followUps.map(([t, w]) => ({ text: t, why: w })),
  };
}

