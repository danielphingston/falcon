import type { Procedure } from "../types";

type Area = Procedure["area"];
type Kinds = Procedure["kinds"];
type Asr = Procedure["assertions"];
type Ind = NonNullable<Procedure["industries"]>;
type FU = Procedure["followUps"];

interface Opts {
  industries?: Ind;
  core?: boolean;
}

/** Local builder to keep the table readable; output is a plain Procedure. */
function p(
  area: Area,
  slug: string,
  kinds: Kinds,
  assertions: Asr,
  text: string,
  why: string,
  followUps: FU,
  opts: Opts = {},
): Procedure {
  const proc: Procedure = { id: `${area}.${slug}`, area, text, why, assertions, kinds, followUps };
  if (opts.industries) proc.industries = opts.industries;
  if (opts.core) proc.core = true;
  return proc;
}

